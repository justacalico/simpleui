  test('lookupAppLocalizations resolves every variant', () {
    expect(
      lookupAppLocalizations(const Locale('en')),
      isA<AppLocalizationsEn>(),
    );
    expect(
      lookupAppLocalizations(const Locale('en', 'GB')),
      isA<AppLocalizationsEnGb>(),
    );
    expect(
      lookupAppLocalizations(const Locale('ga')),
      isA<AppLocalizationsGa>(),
    );
    expect(
      lookupAppLocalizations(const Locale('ru')),
      isA<AppLocalizationsRu>(),
    );
    expect(
      lookupAppLocalizations(const Locale('zh')),
      isA<AppLocalizationsZh>(),
    );
    expect(
      lookupAppLocalizations(
        const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans'),
      ),
      isA<AppLocalizationsZhHans>(),
    );
    expect(
      () => lookupAppLocalizations(const Locale('fr')),
      throwsA(isA<FlutterError>()),
    );
  });
